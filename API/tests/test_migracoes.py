"""B19 - a migracao inicial aplica, bate com os modelos e desfaz.

Roda sempre em SQLite. Em PostgreSQL roda quando TEST_POSTGRES_URL estiver
definida (o CI sobe um Postgres 16 para isso). Use um banco SEPARADO: o
teste desfaz a migracao no fim e apagaria as tabelas do banco de uso.

    TEST_POSTGRES_URL=postgresql+psycopg://copmed:<senha>@localhost:5432/copmed_test pytest tests/test_migracoes.py
"""
import os
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import inspect

from models import Base, create_db_engine

ALEMBIC_INI = Path(__file__).resolve().parents[1] / "alembic.ini"
TABELAS = {
    "medico", "paciente", "pseudonimo", "consulta", "mensagem",
    "transcricao", "documento_soap", "consentimento", "dado_extensao",
    # B26: mapa token -> valor real por consulta, cifrado (US016-CA002).
    "mapa_anonimizacao",
    # B36: auditoria de envios externos, so metadados (US016-CA004).
    "envio_externo",
}


def _alembic_config(url):
    cfg = Config(str(ALEMBIC_INI))
    cfg.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    # Nao deixa o fileConfig do alembic.ini reconfigurar o logging do pytest.
    cfg.attributes["configure_logger"] = False
    return cfg


def _tabelas(url):
    engine = create_db_engine(url)
    try:
        return set(inspect(engine).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()


@pytest.fixture(params=["sqlite", "postgresql"])
def db_url(request, tmp_path):
    if request.param == "sqlite":
        yield f"sqlite:///{(tmp_path / 'migracao.db').as_posix()}"
        return

    url = os.environ.get("TEST_POSTGRES_URL")
    if not url:
        pytest.skip("TEST_POSTGRES_URL nao definida")
    yield url
    # Deixa o banco vazio para a proxima execucao, mesmo se o teste falhar.
    command.downgrade(_alembic_config(url), "base")


def test_upgrade_cria_todas_as_tabelas(db_url):
    command.upgrade(_alembic_config(db_url), "head")

    assert _tabelas(db_url) == TABELAS


def test_migracao_bate_com_os_modelos(db_url):
    cfg = _alembic_config(db_url)
    command.upgrade(cfg, "head")

    # Falha (AutogenerateDiffsDetected) se alguem mudar um modelo sem gerar
    # a migracao correspondente.
    command.check(cfg)


def test_downgrade_remove_tudo_e_upgrade_reaplica(db_url):
    cfg = _alembic_config(db_url)
    command.upgrade(cfg, "head")

    command.downgrade(cfg, "base")
    assert _tabelas(db_url) == set()

    command.upgrade(cfg, "head")
    assert _tabelas(db_url) == TABELAS


def test_modelos_registram_as_mesmas_tabelas_da_migracao():
    assert set(Base.metadata.tables) == TABELAS
